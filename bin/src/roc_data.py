"""Helper functions for ROC.py.

Provides coordinate-based GTF labeling, percentage utilities, and
score+label DataFrame builders for TransCode-based ROC curves.
"""
import sys
from collections import defaultdict

import numpy as np
import pandas as pd
import polars as pl


# ---------------------------------------------------------------------------
# GENCODE-based labeling (coordinate matching)
# ---------------------------------------------------------------------------

def _get_cds_signatures(df: pl.DataFrame, id_attr: str = "transcript_id") -> dict[str, frozenset]:
    """Return {id -> frozenset of (seqname, start, end, strand)} for all CDS rows."""
    cds_df = df.filter(df["feature"] == "CDS")
    cds_map: dict[str, set] = defaultdict(set)
    for row in cds_df.iter_rows(named=True):
        tid = row[id_attr]
        if tid:
            cds_map[tid].add((row["seqname"], int(row["start"]), int(row["end"]), row["strand"]))
    return {tid: frozenset(coords) for tid, coords in cds_map.items()}


def label_query_transcripts(
    query_df: pl.DataFrame,
    reference_df: pl.DataFrame,
    query_id_attr: str = "transcript_id",
    ref_id_attr: str = "transcript_id",
) -> pl.DataFrame:
    """Label each ORF in *query_df* as 'annotated' or 'novel' by CDS coordinate matching.

    An ORF is 'annotated' if its set of CDS intervals exactly matches any ORF in
    *reference_df*. Use ``ref_id_attr="orf_id"`` when the reference is one of the
    study GTFs generated by ``generate_orf_gtf.py``, since those files use ``orf_id``
    (not ``transcript_id``) as the unique ORF identifier.

    Args:
        query_df:       Parsed query GTF (e.g. Ribo-TISH ORFannotate).
        reference_df:   Parsed reference GTF (e.g. study1_orfs.gtf or GENCODE).
        query_id_attr:  Attribute column used to identify each ORF in the query.
        ref_id_attr:    Attribute column used to identify each ORF in the reference.

    Returns:
        Polars DataFrame with columns ``[query_id_attr, "label"]``.
    """
    ref_cds = _get_cds_signatures(reference_df, id_attr=ref_id_attr)
    ref_signatures = set(ref_cds.values())
    print(f"Reference: {len(ref_cds)} ORFs with CDS (grouped by '{ref_id_attr}')", file=sys.stderr)

    qry_cds = _get_cds_signatures(query_df, id_attr=query_id_attr)
    print(f"Query: {len(qry_cds)} ORFs with CDS (grouped by '{query_id_attr}')", file=sys.stderr)

    labels = {
        tid: ("annotated" if sig in ref_signatures else "novel")
        for tid, sig in qry_cds.items()
    }
    n_annotated = sum(1 for v in labels.values() if v == "annotated")
    print(
        f"Annotated: {n_annotated}/{len(labels)} ({100 * n_annotated / len(labels):.1f}%)",
        file=sys.stderr,
    )
    return pl.DataFrame(pd.DataFrame(list(labels.items()), columns=[query_id_attr, "label"]))


# ---------------------------------------------------------------------------
# Bar-plot utility
# ---------------------------------------------------------------------------

def pct_annotated(df: pl.DataFrame) -> float:
    """Return the percentage of rows in *df* where ``label == 'annotated'``."""
    counts = df.group_by("label").agg(pl.len().alias("count"))
    total = counts["count"].sum()
    row = counts.filter(pl.col("label") == "annotated")
    return (row["count"][0] / total * 100) if row.height > 0 else 0.0


# ---------------------------------------------------------------------------
# TransCode ROC data builders
# ---------------------------------------------------------------------------

def build_roc_dfs(
    ribotie_gtf: pl.DataFrame,
    ribotish_gtf: pl.DataFrame,
    ribotie_proteins: dict[str, str],
    ribotish_proteins: dict[str, str],
    phase_seqs: set[str],
) -> tuple[pl.DataFrame, pl.DataFrame]:
    """Build score + binary-label DataFrames for RiboTIE and Ribo-TISH.

    A tool ORF is labelled 1 ('annotated') if its protein sequence is present
    in *phase_seqs* (a TransCode proteomics dataset), otherwise 0 ('novel').
    Ribo-TISH scores are -log10(FrameQvalue) so that higher = more confident.

    Args:
        ribotie_gtf:        Full RiboTIE GTF DataFrame (must contain ``ribotie_score``).
        ribotish_gtf:       Ribo-TISH GTF DataFrame (must contain ``FrameQvalue``).
        ribotie_proteins:   transcript_id -> protein sequence for RiboTIE ORFs.
        ribotish_proteins:  transcript_id -> protein sequence for Ribo-TISH ORFs.
        phase_seqs:         Set of (stop-stripped) protein sequences from one TransCode phase.

    Returns:
        ``(ribotie_roc_df, ribotish_roc_df)`` — each with a score column and an int ``label`` column.
    """
    def _label_df(proteins: dict[str, str]) -> pl.DataFrame:
        return pl.DataFrame({
            "transcript_id": list(proteins.keys()),
            "label": [1 if seq.rstrip("*") in phase_seqs else 0 for seq in proteins.values()],
        })

    ribotie_roc = (
        ribotie_gtf.filter(pl.col("feature") == "CDS")
        .unique("transcript_id")
        .select(["transcript_id", "ribotie_score"])
        .with_columns(pl.col("ribotie_score").cast(pl.Float64))
        .join(_label_df(ribotie_proteins), on="transcript_id", how="left")
        .drop_nulls()
    )

    ribotish_roc = (
        ribotish_gtf.filter(pl.col("feature") == "CDS")
        .unique("transcript_id")
        .select(["transcript_id", "FrameQvalue"])
        .with_columns(pl.col("FrameQvalue").cast(pl.Float64))
        .join(_label_df(ribotish_proteins), on="transcript_id", how="left")
        .select(["FrameQvalue", "label"])
        .drop_nulls()
        .with_columns(
            (-np.log10(pl.col("FrameQvalue"))).alias("score"),
            pl.col("label").cast(pl.Int64),
        )
    )

    return ribotie_roc, ribotish_roc
